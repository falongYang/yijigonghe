import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resetTransientInput, clearPendingAction} from './MVP_Web/js/input-state.js';
const orders={x:5,z:7};
const game={shift:true,box:{x0:1},paused:true,pendingBuild:orders};
const calls=[];
const world={keys:{w:true,arrowleft:true},setEdge:(...a)=>calls.push(['edge',...a]),setDragPan:v=>calls.push(['drag',v])};
const canvas={classList:{remove:v=>calls.push(['class',v])}};
resetTransientInput(game,world,canvas);
assert.deepEqual(world.keys,{w:false,arrowleft:false});
assert.equal(game.shift,false);
assert.equal(game.box,null);
assert.equal(game.paused,true);
assert.equal(game.pendingBuild,orders,'保留玩家未执行的建造意图');
assert.deepEqual(calls,[['edge',0,0,false],['drag',false],['class','grabbing']]);
resetTransientInput(game,world,canvas);
resetTransientInput(game,null,null);
// Cancel an unfinished route without issuing orders, clearing selection or spending resources.
const selection = new Set([7]);
const resources = {bio: 30};
const pending = {pendingBuild:'barracks',pendingAbility:'a_frenzy',pendingPatrol:{pts:[{x:1,z:2},{x:3,z:4}]},selected:selection,res:resources};
const feedback = [];
clearPendingAction(pending,{hideCursor:()=>feedback.push('cursor')},{setBuildHint:v=>feedback.push(['hint',v]),setArmedAbility:v=>feedback.push(['ability',v])});
assert.equal(pending.pendingBuild,null);
assert.equal(pending.pendingAbility,null);
assert.equal(pending.pendingPatrol,null);
assert.equal(pending.selected,selection);
assert.deepEqual([...selection],[7]);
assert.deepEqual(pending.res,{bio:30});
assert.deepEqual(feedback,['cursor',['hint',''],['ability',null]]);
clearPendingAction(pending,null,null);
// Exercise actual entry points: switching modes must discard the old unfinished route.
const source = readFileSync(new URL('./MVP_Web/js/main.js',import.meta.url),'utf8');
const entry = (name,next,context) => {
  const code = source.slice(source.indexOf(`function ${name}(`),source.indexOf(`function ${next}(`));
  return Function(...Object.keys(context),`${code}; return ${name};`)(...Object.values(context));
};
const actionGame = {running:true,paused:false,pendingPatrol:{pts:[{x:1,z:2}]},pendingBuild:null,pendingAbility:null};
const fakeWorld = {hideCursor(){}};
const fakeUI = {setBuildHint(){},setArmedAbility(){},toast(){},showPause(){}};
const context = {game:actionGame,world:fakeWorld,ui:fakeUI,clearPendingAction,Sound:{play(){}},BUILDINGS:{barracks:{name:'巢室'}},ABILITIES:{spell:{name:'技能',cost:10}},sim:{cd:{P:{}},res:{P:{ph:20}}}};
entry('beginBuild','beginAbility',context)('barracks');
assert.equal(actionGame.pendingPatrol,null,'build discards an unfinished patrol');
assert.equal(actionGame.pendingBuild,'barracks');
actionGame.pendingPatrol={pts:[]};
context.sim.res.P.ph=0;
const ability = entry('beginAbility','castAbilityAt',context);
ability('spell');
assert.ok(actionGame.pendingPatrol,'unavailable ability preserves the current action');
assert.equal(actionGame.pendingBuild,'barracks');
context.sim.res.P.ph=20;
ability('spell');
assert.equal(actionGame.pendingPatrol,null);
assert.equal(actionGame.pendingBuild,null);
assert.equal(actionGame.pendingAbility,'spell');
context.playerSel=()=>[7];
entry('beginPatrol','commitPatrol',context)();
assert.equal(actionGame.pendingAbility,null);
assert.deepEqual(actionGame.pendingPatrol,{pts:[]});
context.document={getElementById:()=>null};
entry('togglePause','gotoMenu',context)();
assert.equal(actionGame.paused,true);
assert.equal(actionGame.pendingPatrol,null,'pause must not leave a route to resume accidentally');
console.log('Input reset checks passed');
